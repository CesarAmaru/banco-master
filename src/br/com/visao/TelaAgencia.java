    private void atualizarTabela() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTableAgencia.getModel();
            model.setRowCount(0);

            List<Agencia> listaA = agenciaControle.listarTodos();
            for (Agencia a : listaA) {
                model.addRow(new Object[]{
                    a.getId(),
                    a.getNome(),
                    a.getNumero(),
                    a.getCidade(),
                    a.getUf()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro ao carregar Tabela", JOptionPane.ERROR_MESSAGE);
        }
    }

