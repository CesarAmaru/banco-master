    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if(idAgenciaSelecionada == null){
            throw new IllegalStateException("Nenhuma linha selecionada");
        }
        try{
            int opcao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir a agência selecionada?", "Confirmação", JOptionPane.YES_NO_OPTION);
            
            if(opcao == JOptionPane.YES_OPTION){
                Agencia temp = new Agencia();
                temp.setId(idAgenciaSelecionada);
                agenciaControle.excluir(temp);
                
                JOptionPane.showMessageDialog(this, "Agencia excluída com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
                atualizarTabela();
            }
        }catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Campos Inválidos", JOptionPane.WARNING_MESSAGE);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar no banco: " + e.getMessage(), "Erro no Sistema", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jBexcluirActionPerformed

